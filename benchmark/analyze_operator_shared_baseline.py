#!/usr/bin/env python3

from pathlib import Path


FAMILIES = (
    ("linear", "phase5", "Linear"),
    ("nonlinear", "nonlinear-operator", "Nonlinear"),
)


def parse_evidence(path: Path) -> dict[str, str]:
    values = {}
    for line in path.read_text().splitlines():
        if "=" in line:
            key, value = line.split("=", 1)
            values[key] = value
    return values


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--build", type=Path, required=True)
    parser.add_argument("--evidence", type=Path, required=True)
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--tex", type=Path, required=True)
    arguments = parser.parse_args()

    evidence_lines = [
        "SMAVE_OPERATOR_SHARED_BASELINE 1",
        "contract=two-family-learned-candidate-weighted-jacobi-strict-gate-fallback",
        "families=2",
        "bootstrap_resamples=10000",
        "bootstrap_seed=20260720",
    ]
    data_lines = [
        "% Generated by benchmark/analyze_operator_shared_baseline.py.",
        "workload speedup",
    ]
    tex_lines = [
        "% Generated from build/release/operator-shared-baseline/evidence.txt.",
    ]

    router = parse_evidence(arguments.build / "phase4/family-router-evaluation.txt")
    gate = parse_evidence(arguments.build / "gate-architecture/evidence.txt")
    router_speedup = float(router["paired_median_speedup"])
    router_lower = float(router["paired_speedup_ci95_lower"])
    router_upper = float(router["paired_speedup_ci95_upper"])
    router_win_rate = 100.0 * float(router["paired_win_rate"])
    linear_gate_speedup = float(gate["operator-linear-100.speedup"])
    linear_gate_lower = float(
        gate["operator-linear-100.paired_speedup_ci95_lower"]
    )
    nonlinear_gate_speedup = float(gate["cubic-coupled-nonlinear.speedup"])
    nonlinear_gate_lower = float(
        gate["cubic-coupled-nonlinear.paired_speedup_ci95_lower"]
    )
    evidence_lines.extend(
        [
            f"router.speedup={router_speedup:.17g}",
            f"router.lower={router_lower:.17g}",
            f"router.upper={router_upper:.17g}",
            f"router.win_percent={router_win_rate:.17g}",
            f"linear_gate.speedup={linear_gate_speedup:.17g}",
            f"linear_gate.lower={linear_gate_lower:.17g}",
            f"nonlinear_gate.speedup={nonlinear_gate_speedup:.17g}",
            f"nonlinear_gate.lower={nonlinear_gate_lower:.17g}",
        ]
    )
    tex_lines.extend(
        [
            f"\\newcommand{{\\CalibratedRouterSpeedup}}{{{router_speedup:.3f}}}",
            f"\\newcommand{{\\CalibratedRouterLower}}{{{router_lower:.3f}}}",
            f"\\newcommand{{\\CalibratedRouterUpper}}{{{router_upper:.3f}}}",
            f"\\newcommand{{\\CalibratedRouterWinPercent}}{{{router_win_rate:.1f}}}",
            f"\\newcommand{{\\FusedLinearGateSpeedup}}{{{linear_gate_speedup:.3f}}}",
            f"\\newcommand{{\\FusedLinearGateLower}}{{{linear_gate_lower:.3f}}}",
            f"\\newcommand{{\\FusedNonlinearGateSpeedup}}{{{nonlinear_gate_speedup:.3f}}}",
            f"\\newcommand{{\\FusedNonlinearGateLower}}{{{nonlinear_gate_lower:.3f}}}",
        ]
    )

    total_attempted = 0
    total_failures = 0
    total_gate_mismatches = 0
    for family, directory, command_family in FAMILIES:
        performance = parse_evidence(arguments.build / directory / "performance.txt")
        shared = parse_evidence(
            arguments.build
            / directory
            / "benchmark-traces/operator-shared-hybrid-baseline.txt"
        )
        expected_contract = (
            "paired-complete-runtime-learned-candidate-weighted-jacobi-"
            "strict-gate-fallback"
        )
        if shared.get("contract") != expected_contract:
            raise ValueError(f"{family}: shared baseline contract changed")
        for key, expected in (
            ("candidate", "latent-operator-fp64"),
            ("training_scenarios", "16"),
            ("evaluation_scenarios", "64"),
            ("repetitions", "100"),
            ("attempted", "6400"),
            ("candidate_uses", "6400"),
            ("strict_original_gate", "1"),
            ("independent_runtime_commit_gate_for_accepts", "1"),
            ("mandatory_original_solver_fallback", "1"),
            ("failures", "0"),
            ("gate_mismatches", "0"),
            ("same_accuracy", "1"),
            ("all_failures_retained", "1"),
        ):
            if shared.get(key) != expected:
                raise ValueError(f"{family}: expected {key}={expected}")
        attempts = int(shared["attempted"])
        total_attempted += attempts
        total_failures += int(shared["failures"])
        total_gate_mismatches += int(shared["gate_mismatches"])
        for key, expected in (
            ("online_speedup_semantics", "paired-median-of-per-repetition-ratios"),
            ("break_even_semantics", "training-wall-over-paired-median-saving"),
            ("amortized_speedup_semantics", "paired-representative-projected-ratio"),
            ("break_even_met", "1"),
        ):
            if performance.get(key) != expected:
                raise ValueError(f"{family}: expected {key}={expected}")
        operator_speedup = float(performance["online_speedup"])
        operator_lower = float(performance["paired_speedup_ci95_lower"])
        operator_upper = float(performance["paired_speedup_ci95_upper"])
        if operator_lower <= 1.0:
            raise ValueError(f"{family}: paired operator interval does not prove benefit")
        training_wall_ms = float(performance["training_wall_us"]) / 1000.0
        break_even_queries = int(performance["break_even_queries"])
        baseline_speedup = float(shared["paired_median_speedup"])
        versus_shared = float(
            shared["verified_operator_vs_shared_hybrid_paired_median_speedup"]
        )
        versus_shared_lower = float(
            shared["verified_operator_vs_shared_hybrid_bootstrap_95_lower"]
        )
        versus_shared_upper = float(
            shared["verified_operator_vs_shared_hybrid_bootstrap_95_upper"]
        )
        evidence_lines.extend(
            [
                f"{family}.attempted={attempts}",
                f"{family}.accepted={shared['accepted']}",
                f"{family}.fallbacks={shared['fallbacks']}",
                f"{family}.failures={shared['failures']}",
                f"{family}.gate_mismatches={shared['gate_mismatches']}",
                f"{family}.shared_baseline_speedup={baseline_speedup:.17g}",
                f"{family}.shared_baseline_bootstrap_95_lower={float(shared['bootstrap_95_lower']):.17g}",
                f"{family}.shared_baseline_bootstrap_95_upper={float(shared['bootstrap_95_upper']):.17g}",
                f"{family}.verified_operator_speedup={operator_speedup:.17g}",
                f"{family}.verified_operator_bootstrap_95_lower={operator_lower:.17g}",
                f"{family}.verified_operator_bootstrap_95_upper={operator_upper:.17g}",
                f"{family}.training_wall_ms={training_wall_ms:.17g}",
                f"{family}.break_even_queries={break_even_queries}",
                f"{family}.verified_operator_vs_shared_baseline_speedup={versus_shared:.17g}",
                f"{family}.verified_operator_vs_shared_baseline_bootstrap_95_lower={versus_shared_lower:.17g}",
                f"{family}.verified_operator_vs_shared_baseline_bootstrap_95_upper={versus_shared_upper:.17g}",
                f"{family}.same_accuracy={shared['same_accuracy']}",
            ]
        )
        data_lines.append(f"{command_family}Operator {operator_speedup:.10f}")
        data_lines.append(f"{command_family}SharedBaseline {baseline_speedup:.10f}")
        tex_lines.extend(
            [
                f"\\newcommand{{\\{command_family}OperatorSpeedup}}{{{operator_speedup:.3f}}}",
                f"\\newcommand{{\\{command_family}OperatorLower}}{{{operator_lower:.3f}}}",
                f"\\newcommand{{\\{command_family}OperatorUpper}}{{{operator_upper:.3f}}}",
                f"\\newcommand{{\\{command_family}OperatorTrainingMs}}{{{training_wall_ms:.2f}}}",
                f"\\newcommand{{\\{command_family}OperatorBreakEven}}{{{break_even_queries}}}",
                f"\\newcommand{{\\{command_family}SharedBaselineSpeedup}}{{{baseline_speedup:.3f}}}",
                f"\\newcommand{{\\{command_family}OperatorVsSharedBaseline}}{{{versus_shared:.3f}}}",
                f"\\newcommand{{\\{command_family}OperatorVsSharedBaselineLower}}{{{versus_shared_lower:.3f}}}",
                f"\\newcommand{{\\{command_family}OperatorVsSharedBaselineUpper}}{{{versus_shared_upper:.3f}}}",
                f"\\newcommand{{\\{command_family}SharedAccepted}}{{{shared['accepted']}}}",
                f"\\newcommand{{\\{command_family}SharedFallbacks}}{{{shared['fallbacks']}}}",
            ]
        )

    evidence_lines.extend(
        [
            f"total_attempted={total_attempted}",
            f"total_failures={total_failures}",
            f"total_gate_mismatches={total_gate_mismatches}",
            "END",
        ]
    )
    data_lines.extend(
        [
            f"CalibratedRouter {router_speedup:.10f}",
            f"FusedLinearGate {linear_gate_speedup:.10f}",
            f"FusedNonlinearGate {nonlinear_gate_speedup:.10f}",
        ]
    )
    arguments.evidence.parent.mkdir(parents=True, exist_ok=True)
    arguments.data.parent.mkdir(parents=True, exist_ok=True)
    arguments.tex.parent.mkdir(parents=True, exist_ok=True)
    arguments.evidence.write_text("\n".join(evidence_lines) + "\n")
    arguments.data.write_text("\n".join(data_lines) + "\n")
    arguments.tex.write_text("\n".join(tex_lines) + "\n")


if __name__ == "__main__":
    main()
