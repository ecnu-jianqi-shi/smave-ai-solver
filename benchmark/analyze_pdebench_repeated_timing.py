#!/usr/bin/env python3

import argparse
import random
import statistics
from pathlib import Path


WORKLOADS = (
    "advection",
    "darcy",
    "burgers",
    "diffusion-sorption",
    "shallow-water",
    "ns-incompressible",
    "cfd-1d",
)


def parse_report(path: Path) -> tuple[int, float]:
    values = {}
    for line in path.read_text().splitlines():
        fields = line.split(maxsplit=1)
        if len(fields) == 2:
            values[fields[0]] = fields[1].strip('"')
    if values.get("CROSS_SOLVER_AGREEMENT") != "1":
        raise ValueError(f"{path}: cross-solver agreement failed")
    return int(values["SOLVES"]), float(values["SMAVE_VS_CLASSICAL_SPEEDUP"])


def percentile(sorted_values: list[float], probability: float) -> float:
    position = probability * (len(sorted_values) - 1)
    lower_index = int(position)
    upper_index = min(lower_index + 1, len(sorted_values) - 1)
    fraction = position - lower_index
    return (
        sorted_values[lower_index] * (1.0 - fraction)
        + sorted_values[upper_index] * fraction
    )


def bootstrap_interval(
    values: list[float], seed: int, resamples: int = 10000
) -> tuple[float, float]:
    generator = random.Random(seed)
    medians = []
    for _ in range(resamples):
        sample = [generator.choice(values) for _ in values]
        medians.append(statistics.median(sample))
    medians.sort()
    return percentile(medians, 0.025), percentile(medians, 0.975)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--reports", type=Path, required=True)
    parser.add_argument("--evidence", type=Path, required=True)
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--repetitions", type=int, required=True)
    arguments = parser.parse_args()

    evidence_lines = [
        "SMAVE_PDEBENCH_REPEATED_TIMING 1",
        "contract=repeated-run-level-paired-total-runtime-ratio",
        f"repetitions={arguments.repetitions}",
        f"workloads={len(WORKLOADS)}",
        f"measured_reports={len(WORKLOADS) * arguments.repetitions}",
        f"warmup_reports={len(WORKLOADS)}",
        "bootstrap_resamples=10000",
        "bootstrap_seed_base=20260727",
        "within_run_execution_order=fixed-by-benchmark",
    ]
    data_lines = [
        "% Generated by benchmark/analyze_pdebench_repeated_timing.py.",
        "workload speedup error_minus error_plus",
    ]
    all_lower_bounds_exceed_one = True
    minimum_paired_run_wins = arguments.repetitions

    for workload_index, workload in enumerate(WORKLOADS):
        solve_count = None
        speedups = []
        for repetition in range(1, arguments.repetitions + 1):
            report_path = arguments.reports / (
                f"{workload}-repeat-{repetition:02d}.txt"
            )
            report_solves, speedup = parse_report(report_path)
            if solve_count is None:
                solve_count = report_solves
            elif solve_count != report_solves:
                raise ValueError(f"{report_path}: solve count changed")
            speedups.append(speedup)
        median_speedup = statistics.median(speedups)
        lower, upper = bootstrap_interval(
            speedups, 20260727 + workload_index * 100
        )
        paired_run_wins = sum(value > 1.0 for value in speedups)
        win_rate = paired_run_wins / len(speedups)
        minimum_paired_run_wins = min(minimum_paired_run_wins, paired_run_wins)
        all_lower_bounds_exceed_one = all_lower_bounds_exceed_one and lower > 1.0
        prefix = workload.replace("-", "_")
        evidence_lines.extend(
            [
                f"{prefix}.solves_per_run={solve_count}",
                f"{prefix}.median_speedup={median_speedup:.17g}",
                f"{prefix}.bootstrap_95_lower={lower:.17g}",
                f"{prefix}.bootstrap_95_upper={upper:.17g}",
                f"{prefix}.paired_run_wins={paired_run_wins}",
                f"{prefix}.paired_run_win_rate={win_rate:.17g}",
            ]
        )
        data_lines.append(
            f"{prefix} {median_speedup:.10f} {median_speedup - lower:.10f} "
            f"{upper - median_speedup:.10f}"
        )

    evidence_lines.extend(
        [
            f"all_bootstrap_95_lower_bounds_exceed_one={int(all_lower_bounds_exceed_one)}",
            f"minimum_paired_run_wins={minimum_paired_run_wins}",
            "END",
        ]
    )
    arguments.evidence.parent.mkdir(parents=True, exist_ok=True)
    arguments.data.parent.mkdir(parents=True, exist_ok=True)
    arguments.evidence.write_text("\n".join(evidence_lines) + "\n")
    arguments.data.write_text("\n".join(data_lines) + "\n")


if __name__ == "__main__":
    main()
