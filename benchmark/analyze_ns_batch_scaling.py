#!/usr/bin/env python3

import argparse
import statistics
from pathlib import Path

from analyze_ns_parallel_scaling import bootstrap_median_interval, parse_report


TIME_SLICE_COUNTS = (3, 5, 10, 20, 40)


def paired_throughput_scaling(
    baseline: list[dict[str, float]],
    candidate: list[dict[str, float]],
    elapsed_key: str,
) -> list[float]:
    if len(baseline) != len(candidate):
        raise ValueError("batch series have different repetition counts")
    scaling = []
    for baseline_report, candidate_report in zip(baseline, candidate):
        baseline_throughput = (
            baseline_report["SOLVES"] / baseline_report[elapsed_key]
        )
        candidate_throughput = (
            candidate_report["SOLVES"] / candidate_report[elapsed_key]
        )
        scaling.append(candidate_throughput / baseline_throughput)
    return scaling


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--reports", type=Path, required=True)
    parser.add_argument("--evidence", type=Path, required=True)
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--repetitions", type=int, required=True)
    arguments = parser.parse_args()

    series: dict[int, list[dict[str, float]]] = {}
    for time_slices in TIME_SLICE_COUNTS:
        reports = []
        for repetition in range(1, arguments.repetitions + 1):
            report_path = arguments.reports / (
                f"slices-{time_slices}-repeat-{repetition:02d}.txt"
            )
            report = parse_report(report_path)
            if int(report["TIME_SLICES"]) != time_slices:
                raise ValueError(f"{report_path}: time-slice count mismatch")
            if int(report["REQUESTED_WORKERS"]) != 10:
                raise ValueError(f"{report_path}: requested worker count mismatch")
            reports.append(report)
        series[time_slices] = reports

    baseline = series[TIME_SLICE_COUNTS[0]]
    evidence_lines = [
        "SMAVE_NS_BATCH_SCALING 1",
        "contract=paired-complete-runtime-batch-throughput-scaling",
        "workload=pdebench-incompressible-ns-implicit-helmholtz-subsystem",
        f"repetitions={arguments.repetitions}",
        "time_slices=3,5,10,20,40",
        "solves=12,20,40,80,160",
        "requested_workers=10",
        "accelerate_maximum_threads=1",
        "bootstrap_resamples=10000",
        "bootstrap_seed_base=20260724",
    ]
    data_lines = [
        "% Generated by benchmark/analyze_ns_batch_scaling.py.",
        "solves total total_minus total_plus gate gate_minus gate_plus",
    ]
    maximum_cross_error = 0.0
    maximum_residual = 0.0

    for time_slices in TIME_SLICE_COUNTS:
        reports = series[time_slices]
        total_scaling = paired_throughput_scaling(
            baseline, reports, "SMAVE_SOLVE_SECONDS"
        )
        gate_scaling = paired_throughput_scaling(
            baseline, reports, "SMAVE_GATE_SECONDS"
        )
        seed_offset = time_slices * 100
        total_lower, total_upper = bootstrap_median_interval(
            total_scaling, 20260724 + seed_offset
        )
        gate_lower, gate_upper = bootstrap_median_interval(
            gate_scaling, 20260725 + seed_offset
        )
        total_median = statistics.median(total_scaling)
        gate_median = statistics.median(gate_scaling)
        solves = int(reports[0]["SOLVES"])
        total_per_solve_us = statistics.median(
            [
                report["SMAVE_SOLVE_SECONDS"] * 1.0e6 / report["SOLVES"]
                for report in reports
            ]
        )
        gate_per_solve_us = statistics.median(
            [
                report["SMAVE_GATE_SECONDS"] * 1.0e6 / report["SOLVES"]
                for report in reports
            ]
        )
        maximum_cross_error = max(
            maximum_cross_error,
            max(report["CROSS_SOLVER_RELATIVE_INF_ERROR"] for report in reports),
        )
        maximum_residual = max(
            maximum_residual,
            max(report["SMAVE_MAXIMUM_RELATIVE_RESIDUAL"] for report in reports),
        )
        prefix = f"solves_{solves}"
        evidence_lines.extend(
            [
                f"{prefix}.total_per_solve_median_us={total_per_solve_us:.17g}",
                f"{prefix}.gate_per_solve_median_us={gate_per_solve_us:.17g}",
                f"{prefix}.total_throughput_scaling={total_median:.17g}",
                f"{prefix}.total_bootstrap_95_lower={total_lower:.17g}",
                f"{prefix}.total_bootstrap_95_upper={total_upper:.17g}",
                f"{prefix}.gate_throughput_scaling={gate_median:.17g}",
                f"{prefix}.gate_bootstrap_95_lower={gate_lower:.17g}",
                f"{prefix}.gate_bootstrap_95_upper={gate_upper:.17g}",
            ]
        )
        data_lines.append(
            f"{solves} {total_median:.10f} {total_median - total_lower:.10f} "
            f"{total_upper - total_median:.10f} {gate_median:.10f} "
            f"{gate_median - gate_lower:.10f} {gate_upper - gate_median:.10f}"
        )

    evidence_lines.extend(
        [
            f"maximum_cross_solver_relative_inf_error={maximum_cross_error:.17g}",
            f"maximum_original_equation_relative_residual={maximum_residual:.17g}",
            "cross_solver_agreement=1",
            "END",
        ]
    )
    arguments.evidence.parent.mkdir(parents=True, exist_ok=True)
    arguments.data.parent.mkdir(parents=True, exist_ok=True)
    arguments.evidence.write_text("\n".join(evidence_lines) + "\n")
    arguments.data.write_text("\n".join(data_lines) + "\n")


if __name__ == "__main__":
    main()
