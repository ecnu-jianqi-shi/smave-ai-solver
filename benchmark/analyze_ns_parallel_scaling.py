#!/usr/bin/env python3

import argparse
import math
import random
import statistics
from pathlib import Path


WORKER_COUNTS = (1, 2, 4, 8, 10)
REPORT_KEYS = (
    "SOLVES",
    "TIME_SLICES",
    "REQUESTED_WORKERS",
    "SMAVE_SETUP_SECONDS",
    "SMAVE_KERNEL_SECONDS",
    "SMAVE_GATE_SECONDS",
    "SMAVE_SOLVE_SECONDS",
    "CLASSICAL_SOLVE_SECONDS",
    "CROSS_SOLVER_RELATIVE_INF_ERROR",
    "SMAVE_MAXIMUM_RELATIVE_RESIDUAL",
)


def parse_report(path: Path) -> dict[str, float]:
    values: dict[str, float] = {}
    markers: dict[str, str] = {}
    for line in path.read_text().splitlines():
        fields = line.split(maxsplit=1)
        if len(fields) != 2:
            continue
        key, value = fields
        markers[key] = value.strip('"')
        if key in REPORT_KEYS:
            values[key] = float(value)
    required_markers = {
        "SMAVE_PDEBENCH_NS_INCOMPRESSIBLE": "1",
        "CROSS_SOLVER_AGREEMENT": "1",
    }
    for key, expected in required_markers.items():
        if markers.get(key) != expected:
            raise ValueError(f"{path}: expected {key}={expected}")
    if set(REPORT_KEYS) != set(values):
        missing = sorted(set(REPORT_KEYS) - set(values))
        raise ValueError(f"{path}: missing metrics {missing}")
    values["PARALLEL_WORKERS"] = float(markers["PARALLEL_WORKERS"])
    return values


def percentile(sorted_values: list[float], probability: float) -> float:
    if not sorted_values:
        raise ValueError("cannot compute a percentile of an empty sample")
    position = probability * (len(sorted_values) - 1)
    lower_index = math.floor(position)
    upper_index = math.ceil(position)
    if lower_index == upper_index:
        return sorted_values[lower_index]
    fraction = position - lower_index
    return (
        sorted_values[lower_index] * (1.0 - fraction)
        + sorted_values[upper_index] * fraction
    )


def bootstrap_median_interval(
    values: list[float], seed: int, resamples: int = 10000
) -> tuple[float, float]:
    generator = random.Random(seed)
    medians = []
    for _ in range(resamples):
        sample = [generator.choice(values) for _ in values]
        medians.append(statistics.median(sample))
    medians.sort()
    return percentile(medians, 0.025), percentile(medians, 0.975)


def paired_speedups(
    baseline: list[dict[str, float]],
    candidate: list[dict[str, float]],
    metric: str,
) -> list[float]:
    if len(baseline) != len(candidate):
        raise ValueError("worker series have different repetition counts")
    return [
        baseline_item[metric] / candidate_item[metric]
        for baseline_item, candidate_item in zip(baseline, candidate)
    ]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--reports", type=Path, required=True)
    parser.add_argument("--evidence", type=Path, required=True)
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--repetitions", type=int, required=True)
    arguments = parser.parse_args()

    series: dict[int, list[dict[str, float]]] = {}
    for worker_count in WORKER_COUNTS:
        reports = []
        for repetition in range(1, arguments.repetitions + 1):
            report_path = arguments.reports / (
                f"workers-{worker_count}-repeat-{repetition:02d}.txt"
            )
            report = parse_report(report_path)
            if int(report["PARALLEL_WORKERS"]) != worker_count:
                raise ValueError(f"{report_path}: worker count mismatch")
            reports.append(report)
        series[worker_count] = reports

    baseline = series[1]
    evidence_lines = [
        "SMAVE_NS_PARALLEL_SCALING 1",
        "contract=paired-complete-runtime-worker-scaling",
        "workload=pdebench-incompressible-ns-implicit-helmholtz-subsystem",
        f"repetitions={arguments.repetitions}",
        "workers=1,2,4,8,10",
        "accelerate_maximum_threads=1",
        "bootstrap_resamples=10000",
        "bootstrap_seed_base=20260723",
    ]
    data_lines = [
        "% Generated by benchmark/analyze_ns_parallel_scaling.py.",
        "workers total total_minus total_plus gate gate_minus gate_plus classical",
    ]

    maximum_cross_error = 0.0
    maximum_residual = 0.0
    for worker_count in WORKER_COUNTS:
        reports = series[worker_count]
        total_speedups = paired_speedups(
            baseline, reports, "SMAVE_SOLVE_SECONDS"
        )
        gate_speedups = paired_speedups(
            baseline, reports, "SMAVE_GATE_SECONDS"
        )
        classical_speedups = paired_speedups(
            baseline, reports, "CLASSICAL_SOLVE_SECONDS"
        )
        seed_offset = worker_count * 100
        total_lower, total_upper = bootstrap_median_interval(
            total_speedups, 20260723 + seed_offset
        )
        gate_lower, gate_upper = bootstrap_median_interval(
            gate_speedups, 20260724 + seed_offset
        )
        total_speedup = statistics.median(total_speedups)
        gate_speedup = statistics.median(gate_speedups)
        classical_speedup = statistics.median(classical_speedups)
        total_median_us = statistics.median(
            [report["SMAVE_SOLVE_SECONDS"] * 1.0e6 for report in reports]
        )
        gate_median_us = statistics.median(
            [report["SMAVE_GATE_SECONDS"] * 1.0e6 for report in reports]
        )
        kernel_median_us = statistics.median(
            [report["SMAVE_KERNEL_SECONDS"] * 1.0e6 for report in reports]
        )
        maximum_cross_error = max(
            maximum_cross_error,
            max(report["CROSS_SOLVER_RELATIVE_INF_ERROR"] for report in reports),
        )
        maximum_residual = max(
            maximum_residual,
            max(report["SMAVE_MAXIMUM_RELATIVE_RESIDUAL"] for report in reports),
        )
        prefix = f"worker_{worker_count}"
        evidence_lines.extend(
            [
                f"{prefix}.total_median_us={total_median_us:.17g}",
                f"{prefix}.gate_median_us={gate_median_us:.17g}",
                f"{prefix}.kernel_median_us={kernel_median_us:.17g}",
                f"{prefix}.total_paired_speedup={total_speedup:.17g}",
                f"{prefix}.total_bootstrap_95_lower={total_lower:.17g}",
                f"{prefix}.total_bootstrap_95_upper={total_upper:.17g}",
                f"{prefix}.gate_paired_speedup={gate_speedup:.17g}",
                f"{prefix}.gate_bootstrap_95_lower={gate_lower:.17g}",
                f"{prefix}.gate_bootstrap_95_upper={gate_upper:.17g}",
                f"{prefix}.classical_paired_speedup={classical_speedup:.17g}",
            ]
        )
        data_lines.append(
            f"{worker_count} {total_speedup:.10f} "
            f"{total_speedup - total_lower:.10f} "
            f"{total_upper - total_speedup:.10f} {gate_speedup:.10f} "
            f"{gate_speedup - gate_lower:.10f} "
            f"{gate_upper - gate_speedup:.10f} {classical_speedup:.10f}"
        )

    evidence_lines.extend(
        [
            f"maximum_cross_solver_relative_inf_error={maximum_cross_error:.17g}",
            f"maximum_original_equation_relative_residual={maximum_residual:.17g}",
            "cross_solver_agreement=1",
            "END",
        ]
    )
    arguments.evidence.parent.mkdir(parents=True, exist_ok=True)
    arguments.data.parent.mkdir(parents=True, exist_ok=True)
    arguments.evidence.write_text("\n".join(evidence_lines) + "\n")
    arguments.data.write_text("\n".join(data_lines) + "\n")


if __name__ == "__main__":
    main()
